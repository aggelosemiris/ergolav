#!/usr/bin/env node
// Generates Nocturne's original demo catalogue:
//   public/media/audio/*.mp3   synthesised tracks (CC0, made by this script)
//   public/media/art/**.svg    generative covers and artist images (CC0)
//   supabase/seed.sql          metadata, stream URLs, editorial playlists, a demo account
//
//   node scripts/generate-catalog.mjs            render missing audio + write art and seed
//   node scripts/generate-catalog.mjs --seed-only  skip audio rendering
//   node scripts/generate-catalog.mjs --force      re-render all audio

import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { availableParallelism } from 'node:os';

import { GENRES, ARTISTS, EDITORIAL } from './catalog/data.mjs';
import { albumCover, artistImage } from './catalog/art.mjs';
import { barsFor, durationMs } from './catalog/compose.mjs';
import { hashString } from './catalog/synth.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const AUDIO_DIR = join(ROOT, 'public/media/audio');
const ART_DIR = join(ROOT, 'public/media/art');
const BITRATE = 128;
const LICENCE = 'CC0-1.0 (original composition synthesised for Nocturne)';

export const EDITOR_ID = '00000000-0000-4000-8000-00000000ed17';
export const DEMO_ID = '00000000-0000-4000-8000-0000000de770';
const DEMO_EMAIL = 'demo@nocturne.local';
const DEMO_PASSWORD = 'nocturne-demo';

function uuidFor(kind, slug) {
  const h = createHash('sha1').update(`nocturne:${kind}:${slug}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const sql = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

function buildCatalog() {
  const artists = [];
  const albums = [];
  const tracks = [];
  for (const artist of ARTISTS) {
    const artistId = uuidFor('artist', artist.slug);
    artists.push({ ...artist, id: artistId, image_url: `/media/art/artist/${artist.slug}.svg` });
    for (const album of artist.albums) {
      const albumId = uuidFor('album', album.slug);
      albums.push({ ...album, id: albumId, artist_id: artistId, genre: artist.genre, cover_url: `/media/art/album/${album.slug}.svg` });
      album.tracks.forEach((t, i) => {
        const slug = `${album.slug}-${String(i + 1).padStart(2, '0')}`;
        const bars = barsFor(t.bpm, t.sec);
        const seed = hashString(slug);
        // deterministic, plausible play counts scaled by the artist's audience
        const plays = Math.floor(artist.listeners * (0.4 + ((seed % 1000) / 1000) * 3.2) * (i === 0 ? 1.8 : 1));
        tracks.push({
          id: uuidFor('track', slug), slug, album_id: albumId, artist_id: artistId, genre: artist.genre,
          title: t.title, track_number: i + 1, duration_ms: durationMs(t.bpm, bars), plays,
          url: `/media/audio/${slug}.mp3`,
          spec: { genre: artist.genre, seed, bpm: t.bpm, root: t.root, mode: t.mode, progression: t.prog, bars, swing: t.swing ?? 0 },
        });
      });
    }
  }
  return { artists, albums, tracks };
}

function writeArt({ artists, albums }) {
  mkdirSync(join(ART_DIR, 'album'), { recursive: true });
  mkdirSync(join(ART_DIR, 'artist'), { recursive: true });
  for (const a of albums) writeFileSync(join(ART_DIR, 'album', `${a.slug}.svg`), albumCover(a.slug, a.genre));
  for (const a of artists) writeFileSync(join(ART_DIR, 'artist', `${a.slug}.svg`), artistImage(a.slug, a.genre));
}

function writeSeed({ artists, albums, tracks }) {
  const byTitle = new Map(tracks.map((t) => [t.title, t]));
  const lines = [];
  lines.push('-- Generated by scripts/generate-catalog.mjs. Do not edit by hand.');
  lines.push('-- Original demo catalogue: fictional artists, synthesised audio and generative art (CC0).');
  lines.push('');
  lines.push('insert into public.genres (id, name, color, sort_order) values');
  lines.push(GENRES.map((g, i) => `  (${sql(g.id)}, ${sql(g.name)}, ${sql(g.color)}, ${i})`).join(',\n') + ';');
  lines.push('');
  lines.push('insert into public.artists (id, name, bio, image_url, monthly_listeners) values');
  lines.push(artists.map((a) => `  (${sql(a.id)}, ${sql(a.name)}, ${sql(a.bio)}, ${sql(a.image_url)}, ${a.listeners})`).join(',\n') + ';');
  lines.push('');
  lines.push('insert into public.albums (id, artist_id, title, album_type, release_date, cover_url, genre_id) values');
  lines.push(albums.map((a) => `  (${sql(a.id)}, ${sql(a.artist_id)}, ${sql(a.title)}, ${sql(a.type)}, ${sql(a.date)}, ${sql(a.cover_url)}, ${sql(a.genre)})`).join(',\n') + ';');
  lines.push('');
  lines.push('insert into public.tracks (id, album_id, artist_id, title, track_number, duration_ms, play_count, genre_id) values');
  lines.push(tracks.map((t) => `  (${sql(t.id)}, ${sql(t.album_id)}, ${sql(t.artist_id)}, ${sql(t.title)}, ${t.track_number}, ${t.duration_ms}, ${t.plays}, ${sql(t.genre)})`).join(',\n') + ';');
  lines.push('');
  lines.push('insert into public.track_streams (track_id, url, mime_type, bitrate_kbps, licence, source) values');
  lines.push(tracks.map((t) => `  (${sql(t.id)}, ${sql(t.url)}, 'audio/mpeg', ${BITRATE}, ${sql(LICENCE)}, 'nocturne-generated')`).join(',\n') + ';');
  lines.push('');

  const authUser = (id, email, name, password) => `insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token
) values (
  '00000000-0000-0000-0000-000000000000', ${sql(id)}, 'authenticated', 'authenticated', ${sql(email)},
  ${password ? `extensions.crypt(${sql(password)}, extensions.gen_salt('bf'))` : "''"}, now(),
  '{"provider":"email","providers":["email"]}', ${sql(JSON.stringify({ display_name: name }))}, now(), now(),
  '', '', '', ''
);
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${sql(id)}, ${sql(id)}, ${sql(JSON.stringify({ sub: id, email, email_verified: true }))}::jsonb, 'email', now(), now(), now());`;

  lines.push('-- Editorial account (cannot sign in: no password) that owns the curated playlists.');
  lines.push(authUser(EDITOR_ID, 'editors@nocturne.local', 'Nocturne Editors', null));
  lines.push('');
  lines.push(`-- Local demo account: ${DEMO_EMAIL} / ${DEMO_PASSWORD}. For local development only.`);
  lines.push(authUser(DEMO_ID, DEMO_EMAIL, 'Demo Listener', DEMO_PASSWORD));
  lines.push('');

  const playlistRows = [];
  const itemRows = [];
  EDITORIAL.forEach((p, idx) => {
    const id = uuidFor('playlist', p.slug);
    playlistRows.push(`  (${sql(id)}, ${sql(EDITOR_ID)}, ${sql(p.name)}, ${sql(p.description)}, true, now() - interval '${idx} days')`);
    p.tracks.forEach((title, pos) => {
      const t = byTitle.get(title);
      if (!t) throw new Error(`editorial playlist ${p.slug} references unknown track "${title}"`);
      itemRows.push(`  (${sql(id)}, ${sql(t.id)}, ${pos}, ${sql(EDITOR_ID)}, now() - interval '${idx * 3 + pos} hours')`);
    });
  });
  lines.push('insert into public.playlists (id, owner_id, name, description, is_public, created_at) values');
  lines.push(playlistRows.join(',\n') + ';');
  lines.push('insert into public.playlist_tracks (playlist_id, track_id, position, added_by, added_at) values');
  lines.push(itemRows.join(',\n') + ';');
  lines.push('');
  writeFileSync(join(ROOT, 'supabase/seed.sql'), lines.join('\n'));
}

async function renderAudio(tracks, force) {
  mkdirSync(AUDIO_DIR, { recursive: true });
  const todo = tracks.filter((t) => force || !existsSync(join(AUDIO_DIR, `${t.slug}.mp3`)));
  if (!todo.length) {
    console.log('audio: all tracks already rendered');
    return;
  }
  const workers = Math.max(1, Math.min(availableParallelism(), todo.length));
  console.log(`audio: rendering ${todo.length} tracks on ${workers} workers...`);
  let next = 0;
  let done = 0;
  await Promise.all(
    Array.from({ length: workers }, () =>
      new Promise((resolve, reject) => {
        const w = new Worker(fileURLToPath(import.meta.url), { workerData: { audioDir: AUDIO_DIR } });
        const feed = () => {
          if (next >= todo.length) { w.terminate().then(resolve); return; }
          const t = todo[next++];
          w.postMessage({ slug: t.slug, spec: t.spec });
        };
        w.on('message', (m) => {
          done++;
          console.log(`  [${done}/${todo.length}] ${m.slug} ${(m.bytes / 1024).toFixed(0)} KB in ${m.ms} ms`);
          feed();
        });
        w.on('error', reject);
        feed();
      }),
    ),
  );
}

async function workerMain() {
  const { renderTrack } = await import('./catalog/compose.mjs');
  const { Mp3Encoder } = await import('@breezystack/lamejs');
  parentPort.on('message', ({ slug, spec }) => {
    const started = Date.now();
    const bus = renderTrack(spec);
    const enc = new Mp3Encoder(2, 44100, BITRATE);
    const chunk = 1152;
    const parts = [];
    const l16 = new Int16Array(chunk);
    const r16 = new Int16Array(chunk);
    for (let i = 0; i < bus.length; i += chunk) {
      const n = Math.min(chunk, bus.length - i);
      for (let j = 0; j < n; j++) {
        l16[j] = Math.max(-1, Math.min(1, bus.L[i + j])) * 32767;
        r16[j] = Math.max(-1, Math.min(1, bus.R[i + j])) * 32767;
      }
      const out = enc.encodeBuffer(n === chunk ? l16 : l16.subarray(0, n), n === chunk ? r16 : r16.subarray(0, n));
      if (out.length) parts.push(Buffer.from(out.buffer, out.byteOffset, out.length));
    }
    const end = enc.flush();
    if (end.length) parts.push(Buffer.from(end.buffer, end.byteOffset, end.length));
    const file = Buffer.concat(parts);
    writeFileSync(join(workerData.audioDir, `${slug}.mp3`), file);
    parentPort.postMessage({ slug, bytes: file.length, ms: Date.now() - started });
  });
}

if (!isMainThread) {
  workerMain();
} else {
  const args = new Set(process.argv.slice(2));
  const catalog = buildCatalog();
  writeArt(catalog);
  writeSeed(catalog);
  console.log(`catalogue: ${catalog.artists.length} artists, ${catalog.albums.length} albums, ${catalog.tracks.length} tracks, ${EDITORIAL.length} playlists`);
  console.log('wrote supabase/seed.sql and public/media/art');
  if (!args.has('--seed-only')) await renderAudio(catalog.tracks, args.has('--force'));
}
